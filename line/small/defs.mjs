const f = (n) => +n.toFixed(2);
const P = (pts) => pts.map((p) => p.map(f).join(' '));

// 折线/多边形，每个顶点 [x, y, m]：m>0 圆角半径，m<0 切角长度，缺省尖角
function rp(pts, close = true) {
  const n = pts.length, out = [];
  const unit = (a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy); return [dx / l, dy / l]; };
  for (let i = 0; i < n; i++) {
    const p = pts[i], m = p[2] || 0;
    const open = !close && (i === 0 || i === n - 1);
    if (!m || open) { out.push(`${out.length ? 'L' : 'M'}${f(p[0])} ${f(p[1])}`); continue; }
    const a = unit(p, pts[(i - 1 + n) % n]), b = unit(p, pts[(i + 1) % n]);
    const r = Math.abs(m);
    const p1 = [p[0] + a[0] * r, p[1] + a[1] * r], p2 = [p[0] + b[0] * r, p[1] + b[1] * r];
    out.push(`${out.length ? 'L' : 'M'}${P([p1])}`);
    if (m < 0) out.push(`L${P([p2])}`);
    else { const k = r * 0.2; out.push(`C${P([[p[0] + a[0] * k, p[1] + a[1] * k], [p[0] + b[0] * k, p[1] + b[1] * k], p2]).join(' ')}`); }
  }
  return out.join('') + (close ? 'Z' : '');
}
// 带框：左上切角，其余圆角
const frame = (x0, y0, x1, y1, r = 2.5, c = 2.5) => rp([[x0, y0, -c], [x1, y0, r], [x1, y1, r], [x0, y1, r]]);
// 八边形（圆的替身），rot=22.5 时顶边水平
function octPts(cx, cy, r) {
  return Array.from({ length: 8 }, (_, i) => { const a = ((i * 45 + 22.5) * Math.PI) / 180; return [cx + r * Math.cos(a), cy + r * Math.sin(a)]; });
}
const oct = (cx, cy, r) => 'M' + P(octPts(cx, cy, r)).join('L') + 'Z';
// 开口的八边形弧：从第 a 个顶点走到第 b 个（顺时针，屏幕坐标）
function octArc(cx, cy, r, a, b) {
  const v = octPts(cx, cy, r), s = [];
  for (let i = a; ; i = (i + 1) % 8) { s.push(v[i]); if (i === b % 8) break; }
  return 'M' + P(s).join('L');
}
const dot = (x, y, w = 1.5, h = w) => ({ x, y, w, h });
const box = (x0, y0, x1, y1) => `M${x0} ${y0}H${x1}V${y1}H${x0}Z`;

function star(cx, cy, ro, ri, n = 5, rot = -90) {
  const s = [];
  for (let i = 0; i < n * 2; i++) { const r = i % 2 ? ri : ro, a = ((rot + (i * 180) / n) * Math.PI) / 180; s.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); }
  return 'M' + P(s).join('L') + 'Z';
}
function gear(cx, cy, ro, ri, teeth = 8) {
  const s = [], step = 360 / teeth;
  for (let i = 0; i < teeth; i++) {
    const a0 = i * step - 90;
    for (const [da, r] of [[-step * 0.2, ro], [step * 0.2, ro], [step * 0.3, ri], [step * 0.7, ri]]) {
      const a = ((a0 + da) * Math.PI) / 180; s.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
    }
  }
  return 'M' + P(s).join('L') + 'Z';
}

